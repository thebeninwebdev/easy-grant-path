import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { canAdminTransitionVerification, canUserSubmitVerification, detectDocumentContent, requiredOrganizationDocumentTypes, resolvedOrganizationApprovalStatus, sanitizeDocumentFilename } from "../lib/verification-policy.ts";
const pdf = new Uint8Array([...Buffer.from("%PDF-1.7\nbody\n%%EOF")]);
const png = new Uint8Array([0x89,0x50,0x4e,0x47,0x0d,0x0a,0x1a,0x0a,1,2,3,0x49,0x45,0x4e,0x44]);
const jpg = new Uint8Array([0xff,0xd8,0xff,1,2,0xff,0xd9]);
assert.equal(detectDocumentContent(pdf)?.mimeType, "application/pdf");
assert.equal(detectDocumentContent(png)?.mimeType, "image/png");
assert.equal(detectDocumentContent(jpg)?.mimeType, "image/jpeg");
assert.equal(detectDocumentContent(new Uint8Array(Buffer.from("<script>alert(1)</script>"))), null);
assert.equal(detectDocumentContent(new Uint8Array([0xff,0xd8,0xff,1,2])), null);
assert.deepEqual(requiredOrganizationDocumentTypes("registered"), ["registration_certificate", "authorized_representative_id"]);
assert.deepEqual(requiredOrganizationDocumentTypes("in_progress"), ["authorized_representative_id"]);
assert.equal(resolvedOrganizationApprovalStatus("in_progress"), "provisional");
assert.equal(canUserSubmitVerification("unverified"), true);
assert.equal(canUserSubmitVerification("action_required"), true);
assert.equal(canUserSubmitVerification("pending"), false);
assert.equal(canUserSubmitVerification("verified"), false);
assert.equal(canAdminTransitionVerification("pending", "verified"), true);
assert.equal(canAdminTransitionVerification("pending", "rejected"), true);
assert.equal(canAdminTransitionVerification("verified", "verified"), false);
assert.equal(canAdminTransitionVerification("verified", "action_required"), true);
assert.equal(sanitizeDocumentFilename("../../ passport<script>.pdf", "pdf").includes("/"), false);
const read = (path) => readFile(new URL(`../${path}`, import.meta.url), "utf8");
const [identity, organization, upload, storage, userDownload, adminDownload, admin, service, audit] = await Promise.all([
  read("app/api/verification/identity/route.ts"), read("app/api/verification/organization/route.ts"), read("app/api/verification/uploads/route.ts"), read("lib/file-storage.ts"), read("app/api/verification/files/[...key]/route.ts"), read("app/api/admin/verifications/files/[...key]/route.ts"), read("lib/admin-verifications.ts"), read("lib/verification.ts"), read("models/VerificationAuditEvent.ts"),
]);
for (const route of [identity, organization, upload]) assert.ok(route.indexOf("requireCurrentUserId()") < route.indexOf("await readUploadRequestJson(request)"), "authentication must precede request body processing");
assert.doesNotMatch(storage, /node:fs|writeFile|mkdir/);
assert.match(storage, /access: "private"/);
assert.match(storage, /MAX_DOCUMENT_SIZE = 4 \* 1024 \* 1024/);
assert.match(storage, /detectDocumentContent/);
assert.match(storage, /BLOB_READ_WRITE_TOKEN/);
assert.match(upload, /registerPendingVerificationUpload/);
assert.match(identity + organization, /claimPendingVerificationUpload/);
assert.match(userDownload, /userId,/);
assert.match(userDownload, /Content-Disposition.*attachment/);
assert.match(userDownload, /no-store/);
assert.match(adminDownload, /requireAdmin\(\)/);
assert.match(admin, /verificationFileExists/);
assert.match(admin, /requiredOrganizationDocumentTypes/);
assert.match(admin, /actorId/);
assert.doesNotMatch(admin + service, /development-admin/);
assert.match(admin, /verificationStatus: fromStatus, updatedAt: current\.updatedAt/);
assert.match(service, /canUserSubmitVerification/);
assert.match(service, /CONCURRENT_UPDATE/);
assert.match(audit, /immutable: true/);
assert.match(audit, /denyMutation/);
console.log("verification security tests passed");
